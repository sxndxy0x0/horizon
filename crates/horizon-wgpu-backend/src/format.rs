/// The texture format a `GpuFormat` is stored as, and the bytes per texel the game hands over for it. Three-
/// component formats have no wgpu texture format: they are stored with four, and uploads widen each texel.
pub fn texture(ordinal: u32) -> Option<(T, u32)> {
    Some(match *NAMES.get(ordinal as usize)? {
        "R8_UNORM" => (T::R8Unorm, 1),
        "R8_SNORM" => (T::R8Snorm, 1),
        "RG8_UNORM" => (T::Rg8Unorm, 2),
        "RG8_SNORM" => (T::Rg8Snorm, 2),
        "RGB8_UNORM" => (T::Rgba8Unorm, 3),
        "RGB8_SNORM" => (T::Rgba8Snorm, 3),
        "RGBA8_UNORM" => (T::Rgba8Unorm, 4),
        "RGBA8_SNORM" => (T::Rgba8Snorm, 4),
        "R16_UNORM" => (T::R16Unorm, 2),
        "R16_SNORM" => (T::R16Snorm, 2),
        "RG16_UNORM" => (T::Rg16Unorm, 4),
        "RG16_SNORM" => (T::Rg16Snorm, 4),
        "RGBA16_UNORM" => (T::Rgba16Unorm, 8),
        "RGBA16_SNORM" => (T::Rgba16Snorm, 8),
        "R8_UINT" => (T::R8Uint, 1),
        "R8_SINT" => (T::R8Sint, 1),
        "RG8_UINT" => (T::Rg8Uint, 2),
        "RG8_SINT" => (T::Rg8Sint, 2),
        "RGBA8_UINT" => (T::Rgba8Uint, 4),
        "RGBA8_SINT" => (T::Rgba8Sint, 4),
        "R16_UINT" => (T::R16Uint, 2),
        "R16_SINT" => (T::R16Sint, 2),
        "RG16_UINT" => (T::Rg16Uint, 4),
        "RG16_SINT" => (T::Rg16Sint, 4),
        "RGBA16_UINT" => (T::Rgba16Uint, 8),
        "RGBA16_SINT" => (T::Rgba16Sint, 8),
        "R32_UINT" => (T::R32Uint, 4),
        "R32_SINT" => (T::R32Sint, 4),
        "RG32_UINT" => (T::Rg32Uint, 8),
        "RG32_SINT" => (T::Rg32Sint, 8),
        "RGBA32_UINT" => (T::Rgba32Uint, 16),
        "RGBA32_SINT" => (T::Rgba32Sint, 16),
        "R16_FLOAT" => (T::R16Float, 2),
        "RG16_FLOAT" => (T::Rg16Float, 4),
        "RGBA16_FLOAT" => (T::Rgba16Float, 8),
        "R32_FLOAT" => (T::R32Float, 4),
        "RG32_FLOAT" => (T::Rg32Float, 8),
        "RGBA32_FLOAT" => (T::Rgba32Float, 16),
        "RGB10A2_UNORM" => (T::Rgb10a2Unorm, 4),
        "RGB10A2_UINT" => (T::Rgb10a2Uint, 4),
        "RG11B10_FLOAT" => (T::Rg11b10Ufloat, 4),
        "D32_FLOAT" => (T::Depth32Float, 4),
        "D32_FLOAT_S8_UINT" => (T::Depth32FloatStencil8, 8),
        "D24_UNORM_S8_UINT" => (T::Depth24PlusStencil8, 4),
        "D16_UNORM" => (T::Depth16Unorm, 2),
        "S8_UINT" => (T::Stencil8, 1),
        _ => return None,
    })
}

/// A vertex attribute's format. Three-component 8- and 16-bit attributes are read as four: the game pads them to
/// four bytes per component group, and the shader reads the three it declares.
pub fn vertex(ordinal: u32) -> Option<V> {
    Some(match *NAMES.get(ordinal as usize)? {
        "R8_UNORM" => V::Unorm8,
        "R8_SNORM" => V::Snorm8,
        "RG8_UNORM" => V::Unorm8x2,
        "RG8_SNORM" => V::Snorm8x2,
        "RGB8_UNORM" | "RGBA8_UNORM" => V::Unorm8x4,
        "RGB8_SNORM" | "RGBA8_SNORM" => V::Snorm8x4,
        "R16_UNORM" => V::Unorm16,
        "R16_SNORM" => V::Snorm16,
        "RG16_UNORM" => V::Unorm16x2,
        "RG16_SNORM" => V::Snorm16x2,
        "RGB16_UNORM" | "RGBA16_UNORM" => V::Unorm16x4,
        "RGB16_SNORM" | "RGBA16_SNORM" => V::Snorm16x4,
        "R8_UINT" => V::Uint8,
        "R8_SINT" => V::Sint8,
        "RG8_UINT" => V::Uint8x2,
        "RG8_SINT" => V::Sint8x2,
        "RGB8_UINT" | "RGBA8_UINT" => V::Uint8x4,
        "RGB8_SINT" | "RGBA8_SINT" => V::Sint8x4,
        "R16_UINT" => V::Uint16,
        "R16_SINT" => V::Sint16,
        "RG16_UINT" => V::Uint16x2,
        "RG16_SINT" => V::Sint16x2,
        "RGB16_UINT" | "RGBA16_UINT" => V::Uint16x4,
        "RGB16_SINT" | "RGBA16_SINT" => V::Sint16x4,
        "R32_UINT" => V::Uint32,
        "R32_SINT" => V::Sint32,
        "RG32_UINT" => V::Uint32x2,
        "RG32_SINT" => V::Sint32x2,
        "RGB32_UINT" => V::Uint32x3,
        "RGB32_SINT" => V::Sint32x3,
        "RGBA32_UINT" => V::Uint32x4,
        "RGBA32_SINT" => V::Sint32x4,
        "R16_FLOAT" => V::Float16,
        "RG16_FLOAT" => V::Float16x2,
        "RGB16_FLOAT" | "RGBA16_FLOAT" => V::Float16x4,
        "R32_FLOAT" => V::Float32,
        "RG32_FLOAT" => V::Float32x2,
        "RGB32_FLOAT" => V::Float32x3,
        "RGBA32_FLOAT" => V::Float32x4,
        "RGB10A2_UNORM" => V::Unorm10_10_10_2,
        _ => return None,
    })
}

/// Whether sampling the format can filter (a depth or 32-bit float texture cannot, without features).
pub fn filterable(format: T) -> bool {
    !format.is_depth_stencil_format()
        && matches!(
            format.sample_type(None, None),
            Some(wgpu::TextureSampleType::Float { filterable: true })
        )
}
